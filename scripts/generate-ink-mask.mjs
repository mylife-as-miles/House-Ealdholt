// Original procedural brush mask. The supplied Frostpunk clip is a motion reference only.
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const directory = resolve('main game/public/assets/transitions');
await mkdir(directory, { recursive: true });
let seed = 1337;
const random = () => { seed = Math.imul(seed ^ seed >>> 15, 1 | seed); seed ^= seed + Math.imul(seed ^ seed >>> 7, 61 | seed); return ((seed ^ seed >>> 14) >>> 0) / 4294967296; };
const points = Array.from({ length: 192 }, (_, i) => {
  const a = i / 192 * Math.PI * 2;
  const r = 156 + 22 * Math.sin(a * 5) + 14 * Math.sin(a * 13) + random() * 46;
  return `${(256 + Math.cos(a) * r).toFixed(2)},${(256 + Math.sin(a) * r).toFixed(2)}`;
});
const drops = Array.from({ length: 96 }, () => {
  const a = random() * Math.PI * 2, r = 182 + random() * 63;
  return `<ellipse cx="${256 + Math.cos(a) * r}" cy="${256 + Math.sin(a) * r}" rx="${.6 + random() * 2.8}" ry="${1 + random() * 5}" opacity="${.35 + random() * .65}"/>`;
}).join('');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512"><defs><filter id="bristle" x="-10%" y="-10%" width="120%" height="120%"><feTurbulence type="fractalNoise" baseFrequency=".075" numOctaves="3" seed="17" result="noise"/><feDisplacementMap in="SourceGraphic" in2="noise" scale="13" xChannelSelector="R" yChannelSelector="G"/></filter></defs><g fill="white"><polygon points="${points.join(' ')}" filter="url(#bristle)"/>${drops}</g></svg>`;
await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(directory + '/ink-mask.png');
await writeFile(directory + '/SOURCES.md', '# Ink transition mask\n\nOriginal procedural artwork generated by scripts/generate-ink-mask.mjs. The user-supplied Frostpunk clip informs movement and timing; none of its imagery is copied. 512 x 512 RGBA, shared between desktop and Quest.\n');
console.log('Generated original 512 x 512 ink mask');
